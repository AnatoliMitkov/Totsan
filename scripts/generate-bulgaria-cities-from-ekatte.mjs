import fs from 'node:fs'
import path from 'node:path'

const inputPath = process.argv[2] || 'scratch/ekatte/Ekatte-2025-json'
const outputPath = process.argv[3] || 'src/data/bulgaria-cities.js'

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'))
}

function cleanText(value) {
  return String(value || '').trim().replace(/\s+/g, ' ')
}

const CYRILLIC_TO_LATIN = {
  а: 'a',
  б: 'b',
  в: 'v',
  г: 'g',
  д: 'd',
  е: 'e',
  ж: 'zh',
  з: 'z',
  и: 'i',
  й: 'y',
  к: 'k',
  л: 'l',
  м: 'm',
  н: 'n',
  о: 'o',
  п: 'p',
  р: 'r',
  с: 's',
  т: 't',
  у: 'u',
  ф: 'f',
  х: 'h',
  ц: 'ts',
  ч: 'ch',
  ш: 'sh',
  щ: 'sht',
  ъ: 'a',
  ь: 'y',
  ю: 'yu',
  я: 'ya',
}

function transliterate(value) {
  return cleanText(value)
    .toLocaleLowerCase('bg-BG')
    .split('')
    .map((char) => CYRILLIC_TO_LATIN[char] || char)
    .join('')
}

function slugify(value) {
  return transliterate(value)
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
}

function normalizeOblastName(value) {
  const raw = cleanText(value).replace(/^обл\.\s*/i, '')
  if (raw === 'София (столица)') return 'София град'
  if (raw === 'София') return 'София област'
  return raw
}

function oblastSlug(value) {
  if (value === 'София град') return 'sofia-grad'
  if (value === 'София област') return 'sofia-oblast'
  return slugify(value)
}

function citySearchText(city) {
  return [
    city.name,
    city.nameEn,
    city.slug,
    city.oblast,
    city.oblastSlug,
  ]
    .filter(Boolean)
    .join(' ')
    .toLocaleLowerCase('bg-BG')
}

function validateCities(cities) {
  const ids = new Set()
  const keys = new Set()

  cities.forEach((city) => {
    for (const field of ['id', 'name', 'oblast', 'type', 'slug', 'oblastSlug', 'searchText']) {
      if (!city[field]) {
        throw new Error(`City ${JSON.stringify(city)} is missing ${field}`)
      }
    }

    if (ids.has(city.id)) throw new Error(`Duplicate EKATTE id: ${city.id}`)
    ids.add(city.id)

    const key = `${city.slug}|${city.oblastSlug}`
    if (keys.has(key)) throw new Error(`Duplicate city+oblast key: ${key}`)
    keys.add(key)
  })
}

const sourceStat = fs.statSync(inputPath)
const sourceDir = sourceStat.isDirectory() ? inputPath : path.dirname(inputPath)
const records = readJson(path.join(sourceDir, 'ek_atte.json'))

const cities = records
  .filter((record) => Number(record.kind) === 1)
  .map((record) => {
    const name = cleanText(record.name)
    const oblast = normalizeOblastName(record.oblast_name)
    const nameEn = cleanText(record.name_en)
    const city = {
      id: cleanText(record.ekatte),
      name,
      oblast,
      type: 'city',
      slug: slugify(nameEn || name),
      oblastSlug: oblastSlug(oblast),
      searchText: '',
      nameEn,
      oblastCode: cleanText(record.oblast),
    }
    city.searchText = citySearchText(city)
    return city
  })
  .sort((a, b) => (
    a.oblast.localeCompare(b.oblast, 'bg') ||
    a.name.localeCompare(b.name, 'bg') ||
    a.id.localeCompare(b.id)
  ))

validateCities(cities)

if (cities.length !== 257) {
  console.warn(`Expected 257 cities based on recent NSI EKATTE exports, got ${cities.length}. Verify against the latest official archive.`)
}

const output = `// Generated by scripts/generate-bulgaria-cities-from-ekatte.mjs from the NSI EKATTE JSON archive.
// Source archive page: https://www.nsi.bg/nrnm/ekatte/archive
// Do not edit this list manually; regenerate it from the official archive.

export const BULGARIA_CITIES = ${JSON.stringify(cities, null, 2)}
`

fs.mkdirSync(path.dirname(outputPath), { recursive: true })
fs.writeFileSync(outputPath, output, 'utf8')

console.log(`Generated ${cities.length} Bulgarian cities from NSI EKATTE JSON.`)
console.log(`Output: ${outputPath}`)
