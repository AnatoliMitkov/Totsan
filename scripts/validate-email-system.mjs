const confirmTemplate = await read('supabase/email-templates/confirm-signup.html')
const recoveryTemplate = await read('supabase/email-templates/recovery.html')
const checkEmailPage = await read('src/pages/OnboardingPages.jsx')
const supabaseConfig = await read('supabase/config.toml')

addCheck(
  'Confirm signup template has link, email, and OTP variables',
  containsAll(confirmTemplate, ['{{ .ConfirmationURL }}', '{{ .Email }}', '{{ .Token }}'])
)

addCheck(
  'Recovery template has secure link and email variables',
  containsAll(recoveryTemplate, ['{{ .ConfirmationURL }}', '{{ .Email }}'])
)

addCheck(
  'Check email page supports OTP verification and resend',
  containsAll(checkEmailPage, ['supabase.auth.verifyOtp', "type: 'email'", 'supabase.auth.resend', "type: 'signup'"])
)

addCheck(
  'Check email page offers mailbox shortcuts',
  containsAll(checkEmailPage, ['https://mail.google.com/mail/u/0/#inbox', 'https://outlook.live.com/mail/0/inbox'])
)

addCheck(
  'Check email page can recommend mailbox provider',
  containsAll(checkEmailPage, ['getMailboxOptions', 'recommended', 'Препоръчано'])
)

addCheck(
  'Check email page uses local Totsan background visual',
  containsAll(checkEmailPage, ['CHECK_EMAIL_BACKGROUND', '/Images/images-for-pro-page/01-totsan-pro-hero-visual.png'])
)

addCheck(
  'Local Supabase email confirmations are enabled',
  /\[auth\.email\][\s\S]*enable_confirmations\s*=\s*true/.test(supabaseConfig)
)

addCheck(
  'Local Supabase email OTP length is 6',
  /\[auth\.email\][\s\S]*otp_length\s*=\s*6/.test(supabaseConfig)
)

const previewFiles = [
  'docs-output/email-previews/index.html',
  'docs-output/email-previews/confirm-signup-preview.html',
  'docs-output/email-previews/recovery-preview.html',
  'docs-output/email-previews/inquiry-notification-preview.html',
]

for (const file of previewFiles) {
  addCheck(`Preview exists: ${file}`, await exists(file))
}

for (const file of previewFiles.slice(1)) {
  if (!(await exists(file))) continue
  const html = await read(file)
  addCheck(`Preview has no Supabase placeholders: ${file}`, !hasUnresolvedSupabasePlaceholders(html))
  addCheck(`Preview includes Totsan branding: ${file}`, html.includes('Totsan'))
}

const failed = checks.filter((check) => !check.passed)

await mkdir(reportDir, { recursive: true })
await writeFile(reportPath, buildReport(checks))

for (const check of checks) {
  console.log(`${check.passed ? 'OK' : 'FAIL'} ${check.name}${check.detail ? ` - ${check.detail}` : ''}`)
}

if (failed.length > 0) {
  console.error(`\n${failed.length} email validation check(s) failed.`)
  process.exit(1)
}

console.log(`\nEmail validation passed (${checks.length} checks).`)
console.log(`QA report written to ${path.relative(root, reportPath)}`)
